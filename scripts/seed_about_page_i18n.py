def flatten_locale(code: str, block: dict[str, str | list[str]]) -> dict[str, str]:
    out: dict[str, str] = {}
    caps = block.pop("caps", [])
    for k, v in block.items():
        if isinstance(v, str):
            out[k] = v
    for i, line in enumerate(caps, start=1):
        if i <= 11:
            out[f"about.capability.{i}"] = str(line)
    return out


