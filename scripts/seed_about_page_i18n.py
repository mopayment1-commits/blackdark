        if not block:
            print(f"skip {code}: no seed copy")
            continue
        path = locales_dir / f"{code}.json"
        cat = dict(_load_json_catalog(code) or {})
        for k in EN:
            cat.setdefault(k, EN[k])
        patch = flatten_locale(code, dict(block))
        cat.update(patch)
        path.write_text(json.dumps(cat, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"patched {code}: {len(patch)} about keys")


