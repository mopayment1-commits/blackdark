def main() -> None:
    out = Path("/workspace/docs/remediation/CORRECTIVE_PREVENTIVE_CONTROL_REGISTER.md")
    parts = [HEADER, "## Parent Corrective Controls (CC-001–CC-042)\n"]
    parent_pairs = []
    for t in PARENTS:
        parent_pairs.extend(expand_parent(t))
    sub_pairs = []
    for t in SUBS:
        sub_pairs.extend(expand_sub(t))
    for cid, title, data in parent_pairs:
        if data["Control type"] == "CORRECTIVE":
            parts.append(render_control(cid, title, data))
    parts.append("---\n\n## Parent Preventive Controls (PCtrl-001–PCtrl-042)\n")
    for cid, title, data in parent_pairs:
        if data["Control type"] == "PREVENTIVE":
            parts.append(render_control(cid, title, data))
    parts.append("---\n\n## Sub-Finding Corrective Controls\n")
    for cid, title, data in sub_pairs:
        if data["Control type"] == "CORRECTIVE":
            parts.append(render_control(cid, title, data))
    parts.append("---\n\n## Sub-Finding Preventive Controls\n")
    for cid, title, data in sub_pairs:
        if data["Control type"] == "PREVENTIVE":
            parts.append(render_control(cid, title, data))
    parts.append(FOOTER)
    text = "\n".join(parts)
    out.write_text(text, encoding="utf-8")
    cc_n = text.count("### CC-")
    pc_n = text.count("### PCtrl-")
    field_rows = text.count("| 23 | Stage-boundary declaration |")
    print(f"Wrote {out}")
    print(f"CC={cc_n} PCtrl={pc_n} total={cc_n+pc_n} field_rows_23={field_rows}")


if __name__ == "__main__":
    main()
